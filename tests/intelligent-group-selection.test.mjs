import test from 'node:test';
import assert from 'node:assert/strict';
import {proposeIntelligentGroup as propose,planMeasuredIntelligentLayout as plan,planMeasuredIntelligentLayoutIncremental as incremental,planMeasuredIntelligentLayoutIncrementalCooperative as cooperative} from '../dist/index.js';
const source=(blockKey,documentId='doc')=>({documentId,blockKey});
const block=(id,h=20,extra={})=>({kind:'block',origin:{...source(id),revision:'r'},width:25,unitHeights:[h],splitPolicy:'strict',...extra});
const input=(blocks)=>({schemaVersion:1,revision:'r',fingerprint:'fp',content:{width:100,height:100},sections:[{id:'s',startOn:'continuous',blocks}]});
const choose=(ids,layout='adaptiveRows',groupId='pair')=>({groupId,layout,members:ids.map(id=>source(id))});
const intent=(id,placement)=>({...source(id),placement});
const base=input([block('a'),block('b'),block('c'),block('d')]);
test('explicit adaptive group proposal preserves source order, unrelated intents and constraints',async()=>{
 const o={gap:5,intents:[intent('b',{sizeConstraints:{minWidth:30}}),intent('c',{sideBySide:false,spaceAfter:3}),intent('d',{spaceBefore:7})]};
 const before=JSON.stringify(o),r=plan(base,o);
 assert.equal(r.status,'placed');
 const proposal=propose(r,o,base,choose(['c','b']));
 assert.equal(proposal.status,'proposed');
 assert.deepEqual(proposal.members,[source('b'),source('c')]);
 const [b,c,d]=proposal.options.intents;
 assert.deepEqual(b.placement,{sizeConstraints:{minWidth:30},keepTogetherGroup:'pair',keepTogetherLayout:'adaptiveRows',sideBySide:true});
 assert.deepEqual(c.placement,{sideBySide:false,spaceAfter:3,keepTogetherGroup:'pair',keepTogetherLayout:'adaptiveRows'});
 assert.deepEqual(d,o.intents[2]);
 const grouped=plan(base,proposal.options);
 assert.equal(grouped.status,'placed');
 assert.deepEqual(grouped.fragments.map(f=>f.origin.blockKey),['a','b','c','d']);
 assert.equal(grouped.fragments[1].placement.page,grouped.fragments[2].placement.page);
 assert.equal(grouped.fragments[1].placement.occupiedRect.width,30);
 assert.equal(grouped.fragments[2].placement.occupiedRect.height,23);
 const prior=incremental(base,o),next=incremental(base,proposal.options,prior.snapshot);
 assert.deepEqual(next.result,grouped);
 assert.deepEqual((await cooperative(base,proposal.options,prior.snapshot,()=>{})).result,grouped);
 proposal.options.intents[0].placement.sizeConstraints.minWidth=99;
 assert.equal(JSON.stringify(o),before);
 assert.deepEqual(propose(JSON.parse(JSON.stringify(r)),JSON.parse(before),base,choose(['c','b'])).members,[source('b'),source('c')]);
});

test('reject stale, split, nonconsecutive, cross-document, existing-group and explicit position or row constraints',()=>{
 const check=(i,o,s,reason,expected=i)=>assert.deepEqual(propose(plan(i,o),o,expected,s),{status:'rejected',reason});
 check(base,{},choose(['b','c']),'stale',{...base,revision:'old'});
 check(base,{},choose(['b','b']),'ambiguous');
 check(base,{},choose(['b','missing']),'ambiguous');
 check(base,{},choose(['a','c']),'nonconsecutive');
 check(base,{}, {groupId:'pair',layout:'rows',members:[source('a'),source('b','other')]},'cross-document');
 check(base,{intents:[intent('b',{fixed:{page:0,x:0,y:30}})]},choose(['b','c']),'position-intent');
 check(base,{intents:[intent('b',{preferred:{page:0,x:0,y:30}})]},choose(['b','c']),'position-intent');
 check(base,{intents:[intent('b',{sideBySide:true})]},choose(['b','c'],'vertical'),'horizontal-intent');
 const grouped={intents:['a','b'].map(id=>intent(id,{keepTogetherGroup:'old'}))};
 check(base,grouped,choose(['b','c']),'existing-group');
 check(base,grouped,choose(['c','d'],'vertical','old'),'existing-group');
 const split=input([block('a',20),block('b',60,{unitHeights:[60,60],splitPolicy:'allow'}),block('c')]);
 check(split,{},choose(['b','c']),'ambiguous');
 const broken=input([block('a'),{kind:'pagebreak',origin:{...source('break'),revision:'r'}},block('b')]);
 check(broken,{},choose(['a','b']),'hard-break');
 check(base,{intents:[intent('b',{startNewPage:true})]},choose(['a','b']),'hard-break');
});
test('natural page break is allowed, but group that cannot fit must still fail in planner',()=>{
 const i=input([block('a',60),block('b',60)]);
 const r=plan(i,{});
 assert.equal(r.status,'placed');
 assert.notEqual(r.fragments[0].placement.page,r.fragments[1].placement.page);
 const p=propose(r,{},i,choose(['a','b'],'vertical'));
 assert.equal(p.status,'proposed');
 const failed=plan(i,p.options);
 assert.equal(failed.status,'conflict');
 assert.equal(failed.diagnostic.code,'IL_TOO_LARGE');
 assert.deepEqual(failed.fragments,[]);
});
